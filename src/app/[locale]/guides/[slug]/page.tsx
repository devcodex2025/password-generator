const baseUrl = 'https://www.generatepasswordto.me';

const VPN_GUIDE_VISUAL_BY_SECTION: Partial<Record<number, VpnGuideVisualBlockId>> = {
  0: 'stats',
  1: 'tunnel',
  2: 'scenarios',
  3: 'defense',
  4: 'checklist',
  6: 'myths',
};
const hreflangMap: Record<string, string> = { ua: 'uk' };

/**
 * Guides where the NordVPN offer is shown instead of (or before) NordPass.
 * VPN converts on "breach / privacy / 2FA" intent articles, where the reader
 * is already shopping for a security product.
 */
const VPN_OFFER_GUIDES = new Set<string>([
  'vpn-security-privacy-guide',
  'what-to-do-after-password-breach',
  'two-factor-authentication-basics',
  'password-manager-vs-manual-storage',
  'secure-password-generator-guide',
]);
export const runtime = 'nodejs';
export const revalidate = 3600;

export function generateStaticParams() {
  return SUPPORTED_CONTENT_LANGUAGES.flatMap((locale) =>
    ARTICLE_CATALOG.map((article) => ({ locale, slug: article.slug })),
  );
}

// Unknown guide slugs must 404 and must not be rendered on demand.
export const dynamicParams = false;

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string; slug: string }>;
}): Promise<Metadata> {
  const { locale, slug } = await params;
  const guide = await getCachedGuide(slug, locale);

  if (!guide) {
    return {};
  }

  const isFallbackLocale = locale === 'vi';
  const canonical = isFallbackLocale
    ? `${baseUrl}/en/guides/${slug}`
    : `${baseUrl}/${locale}/guides/${slug}`;

  return {
    title: guide.seoTitle,
    description: guide.seoDescription,
    keywords: guide.keywords,
    alternates: {
      canonical,
      languages: {
        ...Object.fromEntries(
          SUPPORTED_CONTENT_LANGUAGES.filter((lang) => lang !== 'vi').map((lang) => [
            hreflangMap[lang] || lang,
            `${baseUrl}/${lang}/guides/${slug}`,
          ])
        ),
        'x-default': `${baseUrl}/en/guides/${slug}`,
      },
    },
    openGraph: {
      title: guide.seoTitle,
      description: guide.seoDescription,
      url: canonical,
      siteName: 'generatepasswordto.me',
      type: 'article',
      // og:image is auto-generated by opengraph-image.tsx (dynamic per article)
    },
    twitter: {
      card: 'summary_large_image',
      title: guide.seoTitle,
      description: guide.seoDescription,
      // twitter:image is auto-generated by opengraph-image.tsx
    },
    robots: {
      index: !isFallbackLocale,
      follow: true,
      googleBot: {
        index: !isFallbackLocale,
        follow: true,
        'max-video-preview': -1,
        'max-image-preview': 'large',
        'max-snippet': -1,
      },
    },
  };
}

function GuideInterlinkBlock({
  entries,
  locale,
  placement,
}: {
  entries: GuideInterlinkEntry[];
  locale: string;
  placement: GuideInterlinkPlacement;
}) {
  if (!entries.length) {
    return null;
  }

  return (
    <div className="mt-5 rounded-24 border border-[#D1E9FF] dark:border-[#374151] bg-[#F0F8FF] dark:bg-[#0A1A2B] p-4 shadow-sm">
      <p className="text-xs uppercase tracking-wide text-[#2A4E63] dark:text-[#d7f2ff]">
        {getPlacementLabel(locale, placement)}
      </p>
      <div className="mt-2 space-y-2 text-sm text-[#071016] dark:text-[#d6e8ff]">
        {entries.map((entry) => (
          <p key={`${entry.anchorKey}-${entry.kind}-${entry.kind === 'guide' ? entry.target : ''}`}>
            <Link
              href={resolveGuideInterlinkHref(locale, entry)}
              className="font-semibold underline underline-offset-4 decoration-2 decoration-sky-500/70 dark:decoration-sky-300/80 transition-colors hover:text-[#1f3b4c] dark:hover:text-white"
            >
              {getLocalizedInterlinkAnchor(locale, entry.anchorKey)}
            </Link>
          </p>
        ))}
      </div>
    </div>
  );
}

export default async function GuideArticlePage({
  params,
}: {
  params: Promise<{ locale: string; slug: string }>;
}) {
  const { locale, slug } = await params;
  const labels = getGuidesUiLabels(locale);
  const uiCopy = getGuidesUiCopy(locale);
  const guide = await getCachedGuide(slug, locale);
  const allGuides = await getCachedGuides(locale);

  if (!guide) {
    notFound();
  }

  const linkTargets = createGuideLinkTargets(locale, guide.slug, allGuides);
  const interlinkState = createInterlinkState(7);
  const interlinkEntries = getGuideInterlinkEntries(guide.slug);
  const introEntries = interlinkEntries.filter((entry) => entry.placement === 'intro');
  const bodyEntries = interlinkEntries.filter((entry) => entry.placement === 'body');
  const conclusionEntries = interlinkEntries.filter((entry) => entry.placement === 'conclusion');

  const articleCanonical = `${baseUrl}/${locale}/guides/${slug}`;

  const articleJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: guide.seoTitle || guide.title,
    description: guide.seoDescription || guide.excerpt,
    image: guide.image.startsWith('http') ? guide.image : `${baseUrl}${guide.image}`,
    author: {
      '@type': 'Organization',
      name: 'Generate Password To Me',
      url: baseUrl,
    },
    publisher: {
      '@type': 'Organization',
      name: 'Generate Password To Me',
      logo: {
        '@type': 'ImageObject',
        url: `${baseUrl}/images/generate-password-preview.png`,
      },
    },
    datePublished: guide.updatedAt,
    dateModified: guide.updatedAt,
    mainEntityOfPage: {
      '@type': 'WebPage',
      '@id': articleCanonical,
    },
    keywords: guide.keywords?.join(', ') || '',
    inLanguage: hreflangMap[locale] || locale,
  };

  const guideBreadcrumbJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      {
        '@type': 'ListItem',
        position: 1,
        name: labels.home,
        item: `${baseUrl}/${locale}`,
      },
      {
        '@type': 'ListItem',
        position: 2,
        name: labels.guides,
        item: `${baseUrl}/${locale}/guides`,
      },
      {
        '@type': 'ListItem',
        position: 3,
        name: guide.title,
        item: articleCanonical,
      },
    ],
  };

  return (
    <>
      {/* JSON-LD stays outside the client shell so React does not re-render it
          on the client (a <script> inside a client boundary triggers a
          hydration mismatch and is never executed). */}
      <script
        id={`article-schema-${slug}`}
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(articleJsonLd) }}
      />
      <script
        id={`guide-breadcrumb-schema-${slug}`}
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(guideBreadcrumbJsonLd) }}
      />
      <LocalizedPageShell locale={locale}>
      <section className="max-w-4xl mx-auto px-4 pt-10 pb-16">
        <Breadcrumbs
          items={[
            { label: labels.home, href: `/${locale}` },
            { label: labels.guides, href: `/${locale}/guides` },
            { label: guide.title },
          ]}
        />
        <article className="mt-4 rounded-24 border border-[#E5F6FF] dark:border-[#374151] bg-white dark:bg-[#171717] p-6 md:p-8">
          <div className="guide-category-label text-xs uppercase tracking-wide text-[#2A4E63] dark:text-[#9ca3af]">
            {getGuideCategoryLabel(locale, guide.category)}
          </div>
          <h1 className="mt-3 text-3xl md:text-4xl font-bold text-[#071016] dark:text-[#e0e0e0]">{guide.title}</h1>
          <div className="mt-5 relative w-full overflow-hidden rounded-16 aspect-[40/21] bg-[#E5F6FF] dark:bg-[#111827]">
            <Image
              src={guide.image}
              alt={`${guide.title} — ${getGuideCategoryLabel(locale, guide.category)}`}
              fill
              sizes="(max-width: 1024px) 100vw, 896px"
              priority
              fetchPriority="high"
              className="object-cover"
            />
          </div>
          <p className="mt-3 text-[#374151] dark:text-[#c7c7c7]">
            {renderGuideTextWithLinks(guide.excerpt, linkTargets, interlinkState, 'excerpt')}
          </p>

          <GuideInterlinkBlock entries={introEntries} locale={locale} placement="intro" />

          <div className="mt-5 flex flex-wrap gap-3 text-xs text-[#2A4E63] dark:text-[#9ca3af]">
            <span>{uiCopy.minRead(guide.readingMinutes)}</span>
            <span>{uiCopy.updatedLabel}: {formatGuideDate(locale, guide.updatedAt)}</span>
            <span>{uiCopy.authorLabel}: {guide.author}</span>
          </div>

          <div className="mt-8 space-y-8">
            {guide.sections.map((section, index) => (
              <Fragment key={`${section.heading}-${index}`}>
                <section>
                  <h2 className="text-2xl font-semibold text-[#071016] dark:text-[#e0e0e0]">
                    {renderGuideTextWithLinks(section.heading, linkTargets, interlinkState, `heading-${index}`)}
                  </h2>
                  <div className="mt-3 space-y-3">
                    {section.paragraphs.map((paragraph, pIndex) => (
                      <p key={pIndex} className="text-[#374151] dark:text-[#c7c7c7] leading-7">
                        {renderGuideTextWithLinks(paragraph, linkTargets, interlinkState, `paragraph-${index}-${pIndex}`)}
                      </p>
                    ))}
                  </div>
                  {section.bullets && section.bullets.length > 0 ? (
                    <ul className="mt-4 list-disc pl-5 space-y-2 text-[#374151] dark:text-[#c7c7c7]">
                      {section.bullets.map((bullet, bIndex) => (
                        <li key={bIndex}>
                          {renderGuideTextWithLinks(bullet, linkTargets, interlinkState, `bullet-${index}-${bIndex}`)}
                        </li>
                      ))}
                    </ul>
                  ) : null}
                  {slug === 'vpn-security-privacy-guide' && VPN_GUIDE_VISUAL_BY_SECTION[index] ? (
                    <VpnGuideVisualBlocks locale={locale} block={VPN_GUIDE_VISUAL_BY_SECTION[index]!} />
                  ) : null}
                </section>
                {index === 0 && <GuideInterlinkBlock entries={bodyEntries} locale={locale} placement="body" />}
              </Fragment>
            ))}
            <GuideInterlinkBlock entries={conclusionEntries} locale={locale} placement="conclusion" />
          </div>

        </article>

        {/* Affiliate banner (official NordVPN creative, 728x90) */}
        {VPN_OFFER_GUIDES.has(slug) ? (
          <AffiliateBanner
            placement="guide-mid"
            locale={locale}
            product="nordvpn"
            className="mx-auto mt-8 block max-w-3xl"
          />
        ) : null}

        {/* Affiliate recommendation */}
        {VPN_OFFER_GUIDES.has(slug) ? (
          <NordVpnAffiliatePromo
            locale={locale}
            className="mt-8"
            placement={`guide-${slug}`}
          />
        ) : (
          <NordPassAffiliatePromo
            locale={locale}
            className="mt-8"
            placement={`guide-${slug}`}
          />
        )}
      </section>
      </LocalizedPageShell>
    </>
  );
}
